/** Mismo atajo que `registrar_cliente`: la razón social se guarda en mayúsculas. */
function cliente(
  numero_identificacion: string,
  tipo: string,
  razon_social: string,
  ciudad: string | null,
  telefono: string | null,
  email: string | null,
  direccion: string | null,
  diasDesdeRegistro: number,
): Cliente {
  return {
    numero_identificacion,
    razon_social,
    telefono,
    email,
    direccion,
    fecha_registro: haceDias(diasDesdeRegistro),
    fecha_modificacion: null,
    tTipoIdentificacion_codigo_tipo_identificacion: tipo,
    tCiudad_codigo_ciudad: ciudad,
  }
}

